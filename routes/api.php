    |--------------------------------------------------------------------------
    | 8. UPDATE METADATA
    |--------------------------------------------------------------------------
    */

    Route::put(
        '/{id}',
        [ProductMediaController::class, 'update']
    );


    /*
    |--------------------------------------------------------------------------
    | 9. REPLACE FILE
    |--------------------------------------------------------------------------
    */

    Route::put(
        '/{id}/replace',
        [ProductMediaController::class, 'replace']
    );


    /*
    |--------------------------------------------------------------------------
    | 10. DELETE SINGLE
    |--------------------------------------------------------------------------
    */

    Route::delete(
        '/{id}',
        [ProductMediaController::class, 'destroy']
    );


    /*
    |--------------------------------------------------------------------------
    | 11. SET PRIMARY
    |--------------------------------------------------------------------------
    */

    Route::post(
        '/{id}/primary',
        [ProductMediaController::class, 'setPrimary']
