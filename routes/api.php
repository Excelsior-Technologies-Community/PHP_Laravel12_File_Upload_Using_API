    |--------------------------------------------------------------------------
    | 1. LIST MEDIA
    |--------------------------------------------------------------------------
    */

    Route::get(
        '/',
        [ProductMediaController::class, 'index']
    );


    /*
    |--------------------------------------------------------------------------
    | 2. UPLOAD MULTIPLE
    |--------------------------------------------------------------------------
    */

    Route::post(
        '/upload',
        [ProductMediaController::class, 'uploadMultiple']
    );


    /*
    |--------------------------------------------------------------------------
    | 3. BASE64 UPLOAD
    |--------------------------------------------------------------------------
    */

    Route::post(
        '/base64',
        [ProductMediaController::class, 'uploadBase64']
    );


    /*
    |--------------------------------------------------------------------------
    | 4. MEDIA STATISTICS
    |--------------------------------------------------------------------------
    */

    Route::get(
        '/stats',
        [ProductMediaController::class, 'statistics']
